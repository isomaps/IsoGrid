export const catalogs: Record<LocaleCode, Catalog> = { fr, en, de, es, it, nl, pl, ru }

/** Locales prises en charge, dans l'ordre de préférence maison. */
export const SUPPORTED_LOCALES: LocaleCode[] = ['fr', 'en', 'de', 'es', 'it', 'nl', 'pl', 'ru']

export function resolveLocale(input?: string): LocaleCode {
  if (!input) return 'fr'
  const base = input.toLowerCase().split('-')[0] as LocaleCode
  return SUPPORTED_LOCALES.includes(base) ? base : 'fr'
}

/**
 * Traducteur d'une instance. Les surcharges de l'hôte (`options.messages`)
 * priment sur le catalogue.
 */
export class Translator {
  private catalog: Catalog
  constructor(
    private locale: LocaleCode = 'fr',
    private overrides: Partial<Record<string, string>> = {},
  ) {
    this.catalog = catalogs[locale]
  }

  setLocale(locale: LocaleCode): void {
    this.locale = locale
    this.catalog = catalogs[locale]
  }

  getLocale(): LocaleCode {
    return this.locale
  }

  t(key: MessageKey): string {
    return this.overrides[key] ?? this.catalog[key] ?? key
  }

  /** Résout un libellé d'en-tête : clé du catalogue si elle existe, sinon texte brut. */
  header(label: string): string {
    return this.overrides[label] ?? (this.catalog as Record<string, string>)[label] ?? label
  }

  number(value: number, opts?: Intl.NumberFormatOptions): string {
    return new Intl.NumberFormat(this.locale, opts).format(value)
  }

  date(value: Date, opts?: Intl.DateTimeFormatOptions): string {
    return new Intl.DateTimeFormat(this.locale, opts ?? { dateStyle: 'short' }).format(value)
  }
}
